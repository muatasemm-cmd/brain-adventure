List<AdultCategory> buildAdultCategories() => [
  for (final info in _categoryInfo)
    AdultCategory(
      id: info.$1,
      name: info.$2,
      icon: info.$3,
      description: info.$4,
      questions: _buildQuestions(info.$1),
    ),
];

List<AdultQuestion> _buildQuestions(String categoryId) {
  final facts = _facts[categoryId]!;
  return [
    for (var level = 1; level <= adultLevelCount; level++)
      for (var index = 0; index < adultQuestionsPerLevel; index++)
        _question(
          categoryId,
          level,
          index,
          facts[((level - 1) * adultQuestionsPerLevel + index) % facts.length],
        ),
  ];
}

AdultQuestion _question(String categoryId, int level, int index, _Fact fact) {
  final options = [fact.answer, ...fact.wrong];
  final shift = (level + index) % options.length;
  final rotated = [...options.skip(shift), ...options.take(shift)];
  return AdultQuestion(
    id: '${categoryId}_${level}_${index + 1}',
    question: _framedQuestion(fact.question, level, index),
    options: rotated,
    answer: fact.answer,
    explanation: fact.why,
  );
}

String _framedQuestion(String question, int level, int index) {
  final frame = _challengeFrames[(level - 1) ~/ 2];
  final prompts = [
    '$frame: $question',
    'اختر الإجابة الأدق في $frame: $question',
    'ضمن $frame، أجب عن الآتي: $question',
    '$frame يحتاج تركيزك؛ $question',
    'أثبت إتقانك في $frame: $question',
  ];
  return prompts[index];
}

List<AdultQuestion> adultLevelQuestions(AdultCategory category, int level) =>
    category.questions
        .skip((level - 1) * adultQuestionsPerLevel)
        .take(adultQuestionsPerLevel)
        .toList(growable: false);

List<AdultQuestion> adultPlacementQuestions(List<AdultCategory> categories) {
  final questions = <AdultQuestion>[];
  for (var index = 0; index < 15; index++) {
    final categoryIndex = index % categories.length;
    final occurrence = index ~/ categories.length;
    // The first and second question from a category use different base facts,
    // not merely another level's wording of the same fact.
    final questionIndex = categoryIndex + occurrence * adultQuestionsPerLevel;
    questions.add(categories[categoryIndex].questions[questionIndex]);
  }
  return questions;
}
